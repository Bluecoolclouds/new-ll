export function localizeAuthError(
  message: string,
  language: AuthLanguage,
  fallback: string,
): string {
  const normalized = message.trim();
  if (!normalized) return fallback;
  const copy = authCopyFor(language);
  for (const sourceLanguage of ['ru', 'en'] as const) {
    const sourceEntry = Object.entries(authCopy[sourceLanguage]).find(([, text]) => text === normalized);
    if (sourceEntry) return copy[sourceEntry[0] as keyof AuthCopy];
  }
  const copyKey = serverErrorCopyKey[normalized];
  if (copyKey) return copy[copyKey];
  if (/^(?:Invalid input|输入不合法)/i.test(normalized)) return copy.registrationDataInvalid;
  if (/^(?:Invalid params|参数错误|无效参数)$/i.test(normalized)) return copy.registrationDataInvalid;
  const httpError = normalized.match(/^(?:AUTH_HTTP_|Ошибка сервера \()(\d{3})\)?$/);
  if (httpError) return `${copy.serverError} (${httpError[1]})`;
  return normalized;
}
