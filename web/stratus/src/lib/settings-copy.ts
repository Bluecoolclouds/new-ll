export type SettingsCopy = typeof ru;

export function settingsCopyFor(language: WorkspaceLanguage): SettingsCopy {
  return (language === 'en' ? en : ru) as SettingsCopy;
}

export function localizeSettingsText(message: string, language: WorkspaceLanguage, fallback: string): string {
  const normalized = message.trim();
  if (!normalized) return fallback;
  const leading = message.match(/^\s*/)?.[0] ?? '';
  const trailing = message.match(/\s*$/)?.[0] ?? '';
  const keepSpacing = (value: string) => `${leading}${value}${trailing}`;
  const current = settingsCopyFor(language);
  for (const sourceLanguage of ['ru', 'en'] as const) {
    const source = sourceLanguage === 'en' ? en : ru;
    const match = Object.entries(source).find(([, text]) => text === normalized);
    if (match) return keepSpacing(current[match[0] as keyof SettingsCopy]);
    for (const [key, template] of Object.entries(source)) {
      if (!template.includes('{{')) continue;
      const pattern = new RegExp(`^${template.split(/(\{\{\w+\}\})/g).map((part) => part.startsWith('{{') ? '(.+?)' : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('')}$`);
      const values = normalized.match(pattern);
      if (values) {
        let result = current[key as keyof SettingsCopy] as string;
        const placeholders = [...template.matchAll(/\{\{(\w+)\}\}/g)];
        placeholders.forEach((placeholder, index) => {
          result = result.replace(placeholder[0], values[index + 1]);
        });
        return keepSpacing(result);
      }
    }
    for (const [key, text] of Object.entries(source)) {
      if (text.endsWith(' ') && message.startsWith(text)) {
        return `${current[key as keyof SettingsCopy]}${message.slice(text.length)}`;
      }
    }
    if (normalized === source.page && trailing) return keepSpacing(current.page);
    if (normalized === source.usagePercent && trailing) return keepSpacing(current.usagePercent);
    if (normalized === source.of) return keepSpacing(current.of);
    if (normalized === source.keysCount) return keepSpacing(current.keysCount);
    for (const key of ['spacedOf', 'keysSuffix', 'bindOrReplaceEmailSuffix'] as const) {
      if (message === source[key]) return current[key];
    }
    for (const key of ['nameLabel', 'loginLabel', 'groupLabel'] as const) {
      if (message.startsWith(`${source[key]}: `)) return `${current[key]}: ${message.slice(source[key].length + 2)}`;
    }
    for (const key of ['createKeyErrorPrefix', 'updateKeyErrorPrefix', 'deleteKeyErrorPrefix', 'revealKeyErrorPrefix'] as const) {
      if (message.startsWith(`${source[key]}: `)) return `${current[key]}${message.slice(source[key].length)}`;
    }
  }
  return message;
}

export function SettingsTextTree({ language, children }: { language: WorkspaceLanguage; children: ReactNode }) {
  const translate = (node: ReactNode): ReactNode => Children.map(node, (child) => {
    if (typeof child === 'string') return localizeSettingsText(child, language, child);
    if (!isValidElement<{ children?: ReactNode; [key: string]: unknown }>(child)) return child;
    const props: Record<string, unknown> = {};
    for (const attribute of ['aria-label', 'aria-valuetext', 'title', 'placeholder']) {
      const value = child.props[attribute];
      if (typeof value === 'string') props[attribute] = localizeSettingsText(value, language, value);
    }
    if (child.props.children === undefined) return Object.keys(props).length ? cloneElement(child, props) : child;
    return cloneElement(child, props, translate(child.props.children));
  });
  return createElement(Fragment, null, translate(children));
}
