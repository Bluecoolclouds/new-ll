export const workspaceCopy = { ru, en } as const;

export function workspaceCopyFor(language: WorkspaceLanguage): WorkspaceCopy {
  return workspaceCopy[language] as WorkspaceCopy;
}

export function workspaceLocale(language: WorkspaceLanguage): string {
  return language === 'ru' ? 'ru-RU' : 'en-US';
}

export function readWorkspaceLanguage(
  storage?: Pick<Storage, 'getItem'>,
  browserLanguages?: readonly string[],
): WorkspaceLanguage {
  let saved: string | null | undefined;
  let isExplicit = false;
  try {
    const store = storage ?? (typeof window !== 'undefined' ? window.localStorage : undefined);
    saved = store?.getItem('stratus-landing-language');
    isExplicit = store?.getItem('stratus-landing-language-explicit') === '1';
  } catch { /* Browser-language selection still works when storage is blocked. */ }
  if (saved === 'en' || (saved === 'ru' && isExplicit)) return saved;

  const languages = browserLanguages ?? (storage === undefined && typeof navigator !== 'undefined'
    ? navigator.languages?.length ? navigator.languages : [navigator.language]
    : []);
  if (languages.length === 0) return 'ru';
  const supported = languages.find((locale) => /^(ru|en)(-|$)/i.test(locale));
  if (supported) return supported.toLowerCase().startsWith('ru') ? 'ru' : 'en';
  return 'en';
}

export function localizeWorkspaceText(message: string, language: WorkspaceLanguage, fallback: string): string {
  const normalized = message.trim();
  if (!normalized) return fallback;
  const current = workspaceCopyFor(language);
  for (const sourceLanguage of ['ru', 'en'] as const) {
    const sourceEntry = Object.entries(workspaceCopy[sourceLanguage]).find(([, text]) => text === normalized);
    if (sourceEntry) return current[sourceEntry[0] as keyof WorkspaceCopy];
    const source = workspaceCopy[sourceLanguage];
    for (const key of ['redeemErrorPrefix', 'paymentStartErrorPrefix', 'referralTransferErrorPrefix'] as const) {
      if (normalized.startsWith(`${source[key]}: `)) {
        return `${current[key]}${normalized.slice(source[key].length)}`;
      }
    }
  }
  return normalized;
}
